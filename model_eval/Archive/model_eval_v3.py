def get_numbers(input):
  numbers = re.findall(r'\d+', input) #https://www.geeksforgeeks.org/python/re-findall-in-python/
  numbers = int(numbers[0])
  return numbers

"""#Evaluation"""

synethic_text__results=[ ] #store results

print(f"evaluation on output....")
for i, score in  enumerate(random_sample) :

    TA_answer_= generate_response(query=score["query"], llm= ta_model) #retrieval + generation

    judge_model_prompt= judge_prompt.format(     #create judge prompt
        User_question= score['User_question'],
        TA_output_= TA_answer_,
        gold_answer= score['gold_answer']
    )

    judge_output= judge_model.invoke(judge_model_prompt).content #get text output only
    score_= get_numbers(judge_output) #get number from output

    synethic_text__results.append({
        "User_question": score['User_question'],
        "TA_output_": TA_answer_,
        "gold_answer": score['gold_answer'],
        "judge_output": judge_output,
        "score": score_
    })
    print(f"[ {i+1} / {len(random_sample)}] score= {score_}")
    time.sleep( 10) #delay to avoid erroring out

