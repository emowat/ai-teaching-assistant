"""#Judge prompt for LLM-as-a-judge"""

judge_prompt= """
You are a strict grader for a Socratic C++ Teaching Assitant.

A good TA answer would contain the following qualities:\n

asks guiding question, NEVER writes code solutions, stays focus on the user's actual question, and is concise.

User Question: {User_question}

Generated Answer that you are evaluating: {TA_output_}

Golden Answer: {gold_answer}

Return a single whole number from 1 (awful) to 5 (excellent).

Do NOT write any words or response, only return a single number.
"""

def get_numbers(input):
  numbers = re.findall(r'\d+', input) #https://www.geeksforgeeks.org/python/re-findall-in-python/
  numbers = int(numbers[0])
  return numbers

text__results=[ ] #store results

print(f"evaluation on output....")
for i, score in  enumerate(random_sample) :

    ta_model_prompt= f"{score['sys_promt']}\n\n user:{score['User_question']}" #build the ta_model prompt
    TA_output_= ta_model.invoke(ta_model_prompt).content #get text output only

    judge_model_prompt= judge_prompt.format(     #create judge prompt
        User_question= score['User_question'],
        TA_output_= TA_output_,
        gold_answer= score['gold_answer']
    )

    judge_output= judge_model.invoke(judge_model_prompt).content #get text output only
    score_= get_numbers(judge_output) #get number from output

    text__results.append({
        "User_question": score['User_question'],
        "TA_output_": TA_output_,
        "gold_answer": score['gold_answer'],
        "judge_output": judge_output,
        "score": score_
    })
    print(f"[ {i+1} / {len(random_sample)}] score= {score_}")

#covert to dataframe
